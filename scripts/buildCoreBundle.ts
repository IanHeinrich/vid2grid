import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build, type Rollup } from "vite";

const HEADER = "// Generated by npm run bundle from packages/core; do not edit.\n";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const entry = join(repoRoot, "packages", "core", "src", "embed.ts");
const outFile = join(repoRoot, "python", "src", "vid2grid", "_core.js");

function singleChunk(output: Awaited<ReturnType<typeof build>>): Rollup.OutputChunk {
  const [result] = Array.isArray(output) ? output : [output];
  if (result === undefined || !("output" in result)) {
    throw new Error("vite build returned no output to write");
  }
  const chunks = result.output.filter((file) => file.type === "chunk");
  const [chunk] = chunks;
  if (chunk === undefined || chunks.length !== 1 || result.output.length !== 1) {
    throw new Error(`expected exactly one bundled file, got ${result.output.length}`);
  }
  return chunk;
}

const output = await build({
  configFile: false,
  root: repoRoot,
  publicDir: false,
  logLevel: "warn",
  build: {
    lib: { entry, name: "vid2gridCore", formats: ["iife"] },
    target: "es2022",
    minify: false,
    sourcemap: false,
    write: false,
  },
});

writeFileSync(outFile, `${HEADER}${singleChunk(output).code}`, "utf-8");
console.log("wrote python/src/vid2grid/_core.js");
